def _weaker_count(hand_type: str, hand_value: Any) -> int:
    tbl = {
        "豹子": _豹子,
        "同花顺": _同花顺,
        "金花": _金花,
        "顺子": _顺子,
        "对子": _对子,
        "散牌": _散牌,
    }
    m = tbl.get(hand_type)
    if m is None:
        return 0
    return m.get(hand_value, 0)


def win_prob_1v1(hand_type: str, hand_value: Any) -> float:
    w = _weaker_count(hand_type, hand_value)
    return w / _TOTAL


def win_prob_n(hand_type: str, hand_value: Any, opponents: int) -> float:
    w = _weaker_count(hand_type, hand_value)
    if w >= _TOTAL - 1:
        return 1.0
    p = w / _TOTAL
    return p**opponents
